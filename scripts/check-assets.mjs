import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { polyphonic, convert } from 'pinyin-pro';
const data=JSON.parse(await fs.readFile('public/data/curriculum.json','utf8'));
const source=JSON.parse(await fs.readFile('data/curriculum-source.json','utf8'));
source.books.push(JSON.parse(await fs.readFile('data/supplemental-source.json','utf8')));
assert.equal(data.books.length,13);
assert.deepEqual(data.books.map(b=>b.id),source.books.map(b=>b.id),'all source books must be published');
const versionOf=books=>'pep-'+createHash('sha256').update(JSON.stringify(books.map(b=>({id:b.id,edition:b.edition,characters:b.characters.map(c=>[c.id,c.pinyin,c.word,c.distractors])})))).digest('hex').slice(0,16);
assert.equal(data.version,versionOf(data.books),'content version');
assert.deepEqual(data.legacyVersions,[versionOf(data.books.filter(b=>b.id!=='supplement'))],'migration only accepts the exact unchanged original curriculum');
const baseline=JSON.parse(await fs.readFile('data/curriculum-coverage-baseline.json','utf8'));
assert.equal(createHash('sha256').update(await fs.readFile('data/curriculum-source.json')).digest('hex'),baseline.currentSourceSha256,'re-audit coverage after source changes');
const core=new Set(source.books.filter(b=>b.id!=='supplement').flatMap(b=>b.orderedCharacters));
const oldBaseline=new Set([...baseline.books.flatMap(b=>b.characters),...source.books.filter(b=>b.grade>=4).flatMap(b=>b.orderedCharacters)]);
assert.equal(core.size,baseline.currentUnique);
assert.equal(oldBaseline.size,baseline.oldFullBaselineUnique);
const expectedSupplement=new Set([...oldBaseline].filter(c=>!core.has(c)));
assert.deepEqual(expectedSupplement,new Set(baseline.oldMissingFromCurrent),'recorded old-edition difference');
assert.deepEqual(new Set(source.books.find(b=>b.id==='supplement').orderedCharacters),expectedSupplement,'supplement must cover exactly the verified missing characters');
assert.deepEqual(new Set([...core].filter(c=>!oldBaseline.has(c))),new Set(baseline.currentBeyondOldBaseline),'recorded revised-edition additions');
const published=new Set(data.books.flatMap(b=>b.characters.map(c=>c.hanzi)));
assert.deepEqual(published,new Set([...core,...oldBaseline]),'all verified old and revised source characters must be published');
assert.equal(published.size,baseline.unionUnique);
let count=0,stars=0;
for(const book of data.books){
  const original=source.books.find(b=>b.id===book.id);
  assert.deepEqual(book.characters.map(c=>c.hanzi),original.orderedCharacters,`${book.id}: missing, extra or reordered source characters`);
  const originalUnion=new Set([...original.recognitionItems,...original.writingItems].map(x=>x.character));
  assert.deepEqual(new Set(book.characters.map(c=>c.hanzi)),originalUnion,`${book.id}: appendix coverage`);
  const recognition=new Set(original.recognition),writing=new Set(original.writing);
  assert.deepEqual(book.coverage,{recognition:recognition.size,writing:writing.size,overlap:[...writing].filter(c=>recognition.has(c)).length,printedNew:original.printedCounts?.newRecognition??null},`${book.id}: count explanation`);
  assert.equal(new Set(book.characters.map(c=>c.hanzi)).size,book.characters.length,`${book.id}: duplicates`);
  assert.ok(book.edition&&book.sources.length,`${book.id}: provenance`);
  stars+=Math.ceil(book.characters.length/10);
  for(const c of book.characters){
    count++;
    const readings=polyphonic(c.hanzi,{type:'array'})[0];
    assert.ok(readings.includes(c.pinyin),`${c.hanzi}: invalid pinyin ${c.pinyin}`);
    assert.equal(new Set([c.pinyin,...c.distractors]).size,4,`${c.hanzi}: repeated choices`);
    assert.equal(c.distractors.length,3);
    assert.ok(c.distractors.every(p=>!readings.includes(p)),`${c.hanzi}: alternative legal reading in distractors`);
    assert.ok(c.distractors.some(p=>convert(p,{format:'toneNone'})!==convert(c.pinyin,{format:'toneNone'})),`${c.hanzi}: tone-only choices`);
    assert.ok(c.word.includes(c.hanzi)&&c.word.length>1,`${c.hanzi} ${c.pinyin}: missing word context`);
    const stroke=JSON.parse(await fs.readFile(`public/${c.stroke}`,'utf8'));
    assert.ok(stroke.strokes.length&&stroke.strokes.length===stroke.medians.length,`${c.hanzi}: invalid strokes`);
    assert.ok((await fs.stat(`public/${c.audio}`)).size>500,`${c.hanzi}: missing audio`);
  }
}
for(const key of ['reading','reading-pass','reading-retry','trace','recall','done'])assert.ok((await fs.stat(`public/audio/ui/${key}.mp3`)).size>500);
console.log(`Assets verified: ${data.books.length} books, ${count} character positions, ${stars} stars; readings, choices, contexts, strokes and audio checked.`);
